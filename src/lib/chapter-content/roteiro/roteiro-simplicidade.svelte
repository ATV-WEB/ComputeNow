<h2>Uma história simples não é uma história ruim:</h2>
<p>Grandes jogos contam histórias relativamente simples, mas muito bem executadas.</p>
<p>Exemplos:</p>
<ul>
  <li>Undertale: uma criança cai no subsolo e tenta voltar para casa.</li><li>Portal: escapar de um laboratório enquanto uma IA tenta impedir.</li><li>Limbo: um garoto procura sua irmã em um mundo sombrio.</li>
</ul>
<p>O que torna essas histórias memoráveis são os personagens, os diálogos e a forma como os acontecimentos são apresentados.</p>

<h2>O jogador deve entender seu objetivo.</h2>
<p>O jogador quase sempre deve conseguir responder:</p>
<ul>
  <li>Quem eu sou?</li><li>Onde estou?</li><li>O que estou tentando fazer?</li><li>Por que isso importa?</li>
</ul>
<p>Se essas perguntas ficam sem resposta por muito tempo, o jogador pode perder o interesse.</p>

<h2>Evite apresentar muitas informações de uma vez.</h2>
<p>Apresente apenas o necessário para aquele momento.</p>
<p>O restante pode ser descoberto conforme o jogo avança.</p>

<h2>Tenha poucos conflitos principais.</h2>
<p>Não jogue muitos conflitos de uma só vez para o jogador, ele pode ficar perdido.</p>
<p>Em vez disso, tenha um conflito principal em mente e crie conflitos menores que giram em torno dele, que são apresentados no decorrer do jogo</p>

<h2>O jogador não precisa decorar tudo</h2>
<p>O jogador deve lembrar: Do objetivo, dos personagens importantes, dos acontecimentos principais.</p>
