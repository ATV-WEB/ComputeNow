<h2>Ideia principal:</h2>
<p>
  Os melhores plot twists costumam nascer de detalhes aparentemente
  insignificantes.
</p>
<p>O jogador vê aquele elemento dezenas de vezes.</p>
<p>Mas não imagina sua verdadeira importância.</p>
<p>
  Depois da revelação, esse detalhe passa a ter um significado completamente
  diferente.
</p>

<h2>Como aplicar:</h2>
<p>Inclua elementos que pareçam apenas decoração ou ambientação.</p>
<p>Por exemplo:</p>
<ul>
  <li>Um objeto comum;</li>
  <li>Uma frase repetida;</li>
  <li>Uma música;</li>
  <li>Um símbolo;</li>
  <li>Um personagem secundário;</li>
  <li>Um cenário aparentemente irrelevante.</li>
</ul>
<p>Mais tarde, transforme esse detalhe na peça central da história.</p>
<p>Assim o jogador pensa:</p>
<blockquote>"Como eu não percebi isso antes?”</blockquote>

<h2>Exemplo em Dark Souls:</h2>
<p>
  Em Dark Souls, o jogador aprende desde cedo que deve tocar os Sinos do
  Despertar para cumprir uma missão heroica.
</p>
<p>Tudo parece indicar que está restaurando a ordem do mundo.</p>
<p>
  Entretanto, ao conhecer personagens como Kingseeker Frampt e Darkstalker
  Kaathe, percebe que sua jornada fazia parte de um conflito muito maior. Os
  mesmos acontecimentos podem ser interpretados como a manutenção da Era do Fogo
  ou como a continuação de um ciclo que talvez devesse terminar.
</p>
<p>Os sinos nunca mudaram de significado.</p>
<p>Quem mudou foi a compreensão do jogador sobre o papel deles na história.</p>

