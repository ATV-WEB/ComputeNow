<h2>Utilize descrição indireta:</h2>
<p>Em vez de dizer em uma interação:</p>
<blockquote>"Este castelo é antigo."</blockquote>
<p>Diga:</p>
<blockquote>"As paredes estão rachadas e cobertas por musgo."</blockquote>
<p>O jogador chegará sozinho na conclusão de que o castelo é antigo.</p>
