<p>
  Agora que o mundo existe, é hora de escrever como se o próprio mundo estivesse
  falando.
</p>
<p>Cada universo possui uma identidade.</p>

<h2>O vocabulário deve combinar com o cenário:</h2>
<dl>
  <dt>Fantasia medieval:</dt>
  <dd>"Que os deuses iluminem sua jornada."</dd>
  <dt>Ficção científica:</dt>
  <dd>"A estação orbital perdeu comunicação."</dd>
  <dt>Terror:</dt>
  <dd>"Não entre naquele corredor."</dd>
</dl>
<p>
  O mesmo personagem não deveria usar linguagem incompatível com seu universo.
</p>

<h2>Cada personagem deve ter sua própria voz:</h2>
<p>Dois personagens não devem falar exatamente da mesma maneira.</p>

<h2>Pense no contexto:</h2>
<p>O jogador acabou de derrotar um chefe?</p>
<p>Talvez não seja o melhor momento para um diálogo enorme.</p>
<p>Acabou de perder um amigo?</p>
<p>Agora sim um diálogo mais emocional faz sentido.</p>
<p>O ritmo da narrativa influencia a quantidade de texto.</p>

