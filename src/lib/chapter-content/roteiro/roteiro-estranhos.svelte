<h2>Ideia principal:</h2>
<p>Na vida real, pessoas não contam seus segredos para um desconhecido.</p>
<p>Nos jogos, muitos roteiros ignoram isso.</p>
<p>
  O protagonista conhece alguém há cinco minutos e imediatamente recebe toda a
  história de vida daquele personagem.
</p>
<p>Isso torna os diálogos artificiais.</p>

<h2>Confiança deve ser construída:</h2>
<p>Personagens precisam de motivos para confiar no jogador.</p>
<p>Alguns podem:</p>
<ul>
  <li>Desconfiar;</li>
  <li>Esconder informações;</li>
  <li>Mentir;</li>
  <li>Mudar de assunto;</li>
  <li>Responder apenas parte da pergunta.</li>
</ul>
<p>Essa resistência torna os diálogos muito mais naturais.</p>

<h2>Informação é uma recompensa:</h2>
<p>Descobrir a verdade pode funcionar como uma recompensa narrativa.</p>
<p>
  Depois de ajudar um personagem, completar uma missão ou fortalecer a amizade,
  ele finalmente decide contar algo importante.
</p>
<p>O jogador sente que conquistou aquela informação.</p>

<h2>Nem todos conhecem toda a verdade:</h2>
<p>Cada personagem enxerga o mundo de uma forma diferente.</p>
<p>Um guarda sabe coisas diferentes de um historiador.</p>
<p>Um comerciante conhece boatos.</p>
<p>Uma criança interpreta os acontecimentos de forma inocente.</p>
<p>
  Isso cria diferentes perspectivas sobre o mesmo evento e deixa o mundo mais
  convincente.
</p>

<h2>Alguns personagens podem mentir:</h2>
<p>Nem todo NPC precisa ser confiável.</p>
<p>Alguns podem:</p>
<ul>
  <li>Exagerar histórias;</li>
  <li>Esconder seus interesses;</li>
  <li>Culpar outra pessoa;</li>
  <li>Acreditar em informações erradas.</li>
</ul>
<p>
  Isso obriga o jogador a comparar versões diferentes antes de chegar à verdade.
</p>

<h2>Exemplo em Dark Souls:</h2>
<p>Kingseeker Frampt.</p>
<p>
  Quando o jogador finalmente o encontra, Frampt explica apenas parte da
  história e orienta o protagonista a seguir um determinado caminho. Mais tarde,
  é possível encontrar Darkstalker Kaathe, que apresenta uma versão
  completamente diferente dos mesmos acontecimentos.
</p>
<p>
  Nenhum dos dois revela toda a verdade. Cada um omite informações e tenta
  convencer o jogador de que sua visão é a correta. Cabe ao próprio jogador
  decidir em quem acreditar.
</p>

