<h2>Ideia principal:</h2>
<p>A morte de um personagem só funciona quando gera consequências.</p>
<p>
  Matar alguém apenas para surpreender o jogador costuma produzir um impacto
  momentâneo.
</p>
<p>Matar alguém para transformar a história produz um impacto duradouro.</p>

<h2>O erro comum:</h2>
<p>Achar que quanto mais mortes houver, mais dramática será a história.</p>
<p>
  Na prática, o jogador só sente a perda de personagens pelos quais criou apego.
</p>

<h2>Quando uma morte costuma funcionar?</h2>
<ul>
  <li>Quando o jogador conhece bem o personagem;</li>
  <li>Quando ele ainda possui importância para a história;</li>
  <li>Quando sua ausência muda os demais personagens;</li>
  <li>Quando suas consequências permanecem até o final.</li>
</ul>

<h2>Exemplo em Undertale:</h2>
<p>
  Matar personagens causa grandes impactos. Isso altera diálogos, interações e
  eventos dentro do jogo, até mesmo os finais. A rota genocida de Undertale é um
  grande exemplo disso, todo o decorrer do jogo muda se você jogar nessa rota.
  Você enfrentará as lutas mais difíceis do jogo se jogar nessa rota.
</p>

