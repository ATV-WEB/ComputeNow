<p>Antes de matar um personagem, faça duas perguntas:</p>
<ul>
  <li>O jogador realmente teve tempo para se importar com ele?</li>
  <li>O que muda na história depois da morte?</li>
</ul>
<p>
  Se a resposta para a segunda pergunta for "quase nada", talvez esse personagem
  ainda não devesse morrer.
</p>
