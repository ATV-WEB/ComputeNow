<h2>Ideia principal:</h2>
<p>Todo personagem importante deve servir para alguma coisa.</p>
<p>Se remover um personagem da história e nada mudar, provavelmente ele é desnecessário.</p>

<p>Personagens secundários podem:</p>
<ul>
  <li>Ensinar algo;</li>
  <li>Mover a história;</li>
  <li>Criar humor;</li>
  <li>Desafiar o protagonista;</li>
  <li>Representar uma ideia;</li>
  <li>Revelar informações do mundo.</li>
</ul>

<h2>O erro comum:</h2>
<p>Adicionar dezenas de personagens apenas para parecer que o mundo é grande.</p>
<p>Isso dificulta que o jogador se lembre de qualquer um deles.</p>

<h2>Exemplo em Undertale:</h2>
<p>Papyrus representa esperança, mesmo nos momentos mais difíceis.</p>
<p>Sans existe para julgar o jogador, representando o julgamento.</p>
<p>Alphys representa insegurança.</p>
<p>Undyne representa determinação de vencer uma luta impossível e de lutar pela justiça.</p>
<p>Cada personagem possui uma função clara dentro da narrativa.</p>
