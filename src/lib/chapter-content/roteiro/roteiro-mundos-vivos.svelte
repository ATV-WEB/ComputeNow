<p>
  O seu objetivo é fazer o mundo parecer existir mesmo quando o jogador não está
  olhando para ele.
</p>
<p>
  Um mundo vivo transmite a sensação de que seus habitantes têm rotina,
  objetivos e problemas próprios.
</p>

<h2>Os personagens devem ter suas próprias vidas.</h2>
<p>Nem todo NPC deve existir apenas para esperar o jogador.</p>
<p>Dê a impressão de que eles possuem:</p>
<ul>
  <li>Trabalho;</li>
  <li>Família;</li>
  <li>Preocupações;</li>
  <li>Sonhos;</li>
  <li>Rotina;</li>
  <li>Interações com outros personagens.</li>
</ul>
<p>Mesmo pequenos diálogos ajudam nisso.</p>

<h2>Exemplo em Deltarune:</h2>
<p>
  Em mercados durante o jogo, você pode conversar com os vendedores e aprender
  mais sobre eles e o mundo
</p>

