<h2>O mundo deve mudar.</h2>
<p>As ações do jogador podem alterar pequenas coisas.</p>
<p>Exemplos:</p>
<ul>
  <li>Um comércio abre depois de uma missão;</li>
  <li>Uma ponte destruída é reconstruída;</li>
  <li>NPCs mudam de lugar;</li>
  <li>Novas falas aparecem.</li>
</ul>
<p>Essas pequenas mudanças fazem o mundo parecer em movimento.</p>

<h2>Faça eventos acontecerem sem depender do jogador.</h2>
<p>Nem tudo precisa acontecer porque o protagonista chegou.</p>
<p>Exemplos:</p>
<ul>
  <li>Uma guerra já está acontecendo;</li>
  <li>Um personagem comenta algo que aconteceu ontem;</li>
  <li>Alguém diz que perdeu uma oportunidade porque o jogador demorou.</li>
</ul>
<p>Isso cria a sensação de que o tempo continua passando.</p>

<h2>Mostre consequências.</h2>
<p>Quando algo importante acontece, o mundo deve reagir.</p>
<p>Se um vilão destrói uma vila:</p>
<ul>
  <li>Moradores comentam o ocorrido;</li>
  <li>Refugiados aparecem em outras cidades;</li>
  <li>Comerciantes vendem menos produtos;</li>
  <li>Soldados reforçam a segurança.</li>
</ul>
<p>Isso torna a narrativa mais crível.</p>

<h2>Use detalhes ambientais.</h2>
<p>Preencha o ambiente com detalhes que indiquem o contexto do local.</p>
<p>Você pode fazer detalhes de ambientes mudarem de acordo com o contexto</p>

<h2>Exemplo em Pokémon Black/White/Black 2/White 2:</h2>
<p>
  Na cidade de Lacunosa, existe uma lenda de um monstro que invade a cidade e
  devora os habitantes de noite. De dia, os habitantes estão nas ruas da cidade,
  mas de noite todos entram em suas casas. Isso não acontece em nenhum outro
  local dos jogos.
</p>
