<p>
  Uma das maiores diferenças entre roteiro para jogos e livros é que o jogador
  quer jogar.
</p>
<p>
  Ler faz parte da experiência, mas não deve interromper o ritmo constantemente.
</p>

<h2>Mostre, não diga.</h2>
<p>Em vez de escrever:</p>
<blockquote>
  "O reino caiu há trezentos anos depois de uma guerra iniciada pelo antigo
  rei..."
</blockquote>
<p>
  Mostre isso através de: ruínas, monumentos, diálogos, documentos encontrados,
  cenário.
</p>
<p>
  Por exemplo: Em Undertale, é um desejo comum de todos os monstros habitantes
  do subterrâneo que eles querem escapar para a superfície. O jogador consegue
  aprender mais sobre isso interagindo com flores de eco (flores que gravam as
  vozes de quem fala)
</p>

<img src="/ComputeNow/images/chapter-content/roteiro/Imagem3.jpg" alt="" />

<p>
  O jogador gosta de descobrir informações. Essa é a regra “Mostre, não diga”.
</p>

<h2>Um diálogo deve ter um objetivo!</h2>
<p>Antes de escrever qualquer conversa, pergunte:</p>
<p>Ela serve para:</p>
<ul>
  <li>desenvolver um personagem?</li>
  <li>ensinar alguma mecânica?</li>
  <li>avançar a história?</li>
  <li>criar humor?</li>
  <li>criar emoção?</li>
</ul>
<p>Se não fizer nenhuma dessas coisas, talvez possa ser removida.</p>

<h2>Corte repetições de diálogos:</h2>
<p>Evite explicar a mesma informação várias vezes.</p>
<p>Confie na inteligência do jogador.</p>
<p>
  Você pode fazer com que o jogador possa ouvir a repetição de uma informação de
  forma opcional, como interagir com um NPC opcional.
</p>
