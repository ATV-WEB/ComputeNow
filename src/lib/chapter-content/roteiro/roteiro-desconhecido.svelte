<h2>Ideia principal:</h2>
<p>O desconhecido é uma das maiores ferramentas para criar suspense.</p>
<p>
  Quando o jogador não sabe exatamente o que existe à frente, sua imaginação
  começa a preencher as lacunas. Muitas vezes, o que ele imagina é mais
  intrigante do que qualquer explicação imediata.
</p>
<p>
  Por isso, nem sempre é necessário mostrar o perigo. Basta sugerir sua
  existência.
</p>

<h2>Crie expectativa antes da revelação:</h2>
<p>
  Antes de apresentar um personagem, um monstro ou um local importante, faça o
  jogador ouvir falar dele.
</p>
<p>Isso pode acontecer por meio de:</p>
<ul>
  <li>NPCs comentando sobre o assunto;</li>
  <li>Rastros deixados no cenário;</li>
  <li>Ruídos vindos de uma sala inacessível;</li>
  <li>Mensagens ou documentos antigos.</li>
</ul>
<p>Quando finalmente acontece o encontro, ele tem muito mais impacto.</p>

<h2>Exemplo em Undertale:</h2>
<p>
  Asgore é mencionado várias vezes antes dele aparecer no final do jogo,
  construindo antecipação para quando o jogador finalmente encontrar ele.
</p>

