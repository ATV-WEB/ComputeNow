<h2>O jogador deve se preparar sem saber para quê:</h2>
<p>
  Um ótimo tipo de suspense acontece quando o jogador percebe que algo
  importante está para acontecer, mas não sabe exatamente o quê.
</p>
<p>Isso faz com que ele observe o ambiente com mais atenção.</p>
<p>Por exemplo:</p>
<ul>
  <li>Uma porta gigantesca em um castelo;</li>
  <li>Uma arena completamente vazia;</li>
  <li>Um corredor excessivamente silencioso;</li>
  <li>Um NPC dizendo apenas:<br />"Tenha cuidado ao seguir em frente."</li>
</ul>
<p>Nada disso explica o perigo, mas tudo prepara o jogador emocionalmente.</p>

<h2>Não responda todas as perguntas imediatamente:</h2>
<p>É normal que o jogador tenha dúvidas.</p>
<p>Na verdade, isso é desejável.</p>
<p>
  Apenas tome cuidado para que essas dúvidas pareçam intencionais e que sejam
  respondidas no momento certo.
</p>
<p>Mistério prende. Confusão afasta.</p>
