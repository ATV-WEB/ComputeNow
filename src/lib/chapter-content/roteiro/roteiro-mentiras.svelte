<h2>Ideia principal:</h2>
<p>Nem toda informação apresentada ao jogador precisa ser verdadeira.</p>
<p>Personagens podem:</p>
<ul>
  <li>Mentir;</li>
  <li>Esconder informações;</li>
  <li>Acreditar em algo errado;</li>
  <li>Interpretar os fatos de forma equivocada.</li>
</ul>
<p>
  Isso torna o mundo mais real e cria oportunidades naturais para reviravoltas.
</p>

<h2>Como aplicar:</h2>
<p>Pergunte sempre:</p>
<blockquote>"Quem está contando essa informação?"</blockquote>
<p>Depois:</p>
<blockquote>"Essa pessoa realmente sabe a verdade?"</blockquote>
<p>Um personagem pode estar completamente convencido de algo falso.</p>

<h2>Exemplo em Hollow Knight:</h2>
<p>
  Durante boa parte do jogo, parece que o Hollow Knight é simplesmente o
  responsável pela Infecção.
</p>
<p>
  Mais tarde, descobre-se que ele próprio é uma vítima: foi criado para servir
  como recipiente da Infecção, mas falhou por possuir emoções.
</p>
<p>A maioria dos personagens não estava tentando enganar o jogador.</p>
<p>Eles simplesmente não conheciam toda a verdade.</p>

