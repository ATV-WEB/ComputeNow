<h2>Ideia principal</h2>
<p>Os melhores vilões não acreditam que são maus.</p>
<p>
  Eles acreditam que estão certos, ou pelo menos acreditam que estão fazendo a
  melhor escolha.
</p>
<p>
  Quando um vilão possui uma motivação compreensível, ele deixa de ser apenas um
  obstáculo e se torna um personagem.
</p>

<h2>O erro comum:</h2>
<p>Vilões que querem destruir o mundo simplesmente porque sim.</p>
<p>Sem objetivo.</p>
<p>Sem passado.</p>
<p>Sem justificativa.</p>

<h2>Exemplo em Undertale:</h2>
<p>Flowey deseja sentir alguma coisa novamente.</p>
<p>Sua crueldade nasce da incapacidade de sentir empatia.</p>
<p>
  Isso não justifica suas ações, mas explica por que ele age daquela maneira.
</p>

