<h2>Exemplo em Dark Souls:</h2>
<p>Muitos chefes não são maus.</p>
<p>Eles apenas continuam cumprindo um dever antigo.</p>
<p>Alguns lutam para proteger algo.</p>
<p>Outros simplesmente enlouqueceram com o tempo.</p>
<p>Isso faz com que o jogador sinta pena de vários inimigos.</p>

<h2>Pergunte:</h2>
<p>
  Se eu contasse essa história pelo ponto de vista do vilão, ele ainda pareceria
  o herói?
</p>
<p>Se a resposta for sim, provavelmente ele possui uma boa motivação.</p>
