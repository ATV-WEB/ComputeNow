<h2>Ideia principal:</h2>
<p>Nem toda história precisa ser contada em ordem.</p>
<p>Em muitos jogos, o jogador monta a narrativa como um quebra-cabeça, encontrando pequenas informações espalhadas pelo mundo.</p>
<p>Cada fragmento faz sentido sozinho, mas, quando unidos, revelam uma história muito maior.</p>

<h2>Divida as informações:</h2>
<p>Em vez de entregar uma longa explicação, distribua pequenas revelações durante a aventura.</p>
<p>Essas informações podem aparecer em:</p>
<ul>
  <li>Diálogos;</li><li>Objetos;</li><li>Descrições de itens;</li><li>Cenários;</li><li>Documentos;</li><li>Eventos do próprio jogo.</li>
</ul>
<p>Cada descoberta deve fazer o jogador pensar:</p>
<blockquote>"Agora tudo faz mais sentido.”</blockquote>

<h2>Recompense quem presta atenção:</h2>
<p>Jogadores atentos devem perceber conexões antes dos demais.</p>
<p>Isso cria uma sensação muito satisfatória de descoberta.</p>
<p>Não é preciso esconder informações de forma injusta; basta espalhá-las de maneira natural para que o próprio jogador faça as ligações.</p>

<h2>Exemplo em Dark Souls:</h2>
<p>Grande parte da história de Dark Souls é descoberta por meio de descrições de itens, diálogos e observação do cenário.</p>
<p>Cada informação parece pequena isoladamente, mas, quando o jogador conecta esses fragmentos, compreende a origem de personagens, guerras, reinos e conflitos.</p>
<p>O jogo confia na capacidade do jogador de montar esse quebra-cabeça em vez de explicar tudo diretamente.</p>
