<h2>Ideia principal:</h2>
<p>Uma das maneiras mais eficientes de prender o jogador é fazer com que ele perceba que entrou em uma história que já estava acontecendo antes de sua chegada.</p>
<p>O mundo não deve parecer criado apenas para receber o protagonista. Pelo contrário: ele precisa transmitir a sensação de que existe uma história muito maior acontecendo.</p>
<p>Em vez de explicar imediatamente qual é o problema do mundo, permita que o jogador descubra isso aos poucos.</p>
<p>Isso cria uma pergunta constante:</p>
<blockquote>"O que aconteceu aqui?"</blockquote>
<p>Enquanto essa pergunta não é respondida, a curiosidade mantém o jogador avançando.</p>

<h2>Faça o jogador montar o quebra-cabeça:</h2>
<p>Cada descoberta deve responder uma pergunta e criar outra.</p>

<h2>Exemplo em Undertale:</h2>
<p>Primeiro, o jogador conhece o Flowey, uma flor dourada.</p>
<p>Depois, o jogador aprende sobre Asriel, monstro que faleceu sobre o jardim de flores douradas.</p>
<p>Após isso, é mostrado que a cientista Alphys injetou o poder da determinação nas flores douradas, assim surgindo Flowey.</p>
<p>E no final da rota pacifista do jogo, há a revelação de que Flowey é Asriel.</p>
<p>De pouco a pouco, o jogador pode juntar as peças e chegar a conclusão de que Flowey tem uma origem relacionada à Asriel antes dessa revelação.</p>

<h2>O mundo deve existir independentemente do jogador:</h2>
<p>NPCs devem conversar entre si.</p>
<p>Eventos importantes devem ter acontecido antes do protagonista nascer.</p>
<p>Ruínas, documentos, monumentos e cicatrizes no cenário ajudam a mostrar que aquele mundo possui história própria.</p>
<p>Quando o jogador percebe isso, sente que está explorando um lugar real, e não um palco construído apenas para sua aventura.</p>
