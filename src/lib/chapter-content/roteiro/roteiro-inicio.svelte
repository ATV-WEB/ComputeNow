<p>
  O jogo faz parecer inicialmente que Flowey é um amigo te ensinando o tutorial
  do jogo, mas rapidamente surpreende o jogador ao revelar que ele é um vilão.
</p>

<h2>Faça o jogador perguntar "o que aconteceu aqui?"</h2>
<p>Um cenário pode contar uma história sem precisar de diálogos.</p>
<p>Alguns exemplos:</p>
<ul>
  <li>Uma cidade abandonada;</li>
  <li>Uma espada fincada em uma pedra;</li>
  <li>casas destruídas.</li>
</ul>
<p>Esses elementos fazem o jogador imaginar os acontecimentos.</p>

<h2>Apresente um objetivo claro rapidamente.</h2>
<p>
  Mesmo que o grande conflito demore a aparecer, o jogador precisa saber o que
  fazer primeiro.
</p>
<p>Objetivos simples funcionam muito bem:</p>
<ul>
  <li>Encontrar alguém;</li>
  <li>Escapar de um local;</li>
  <li>Chegar à cidade.</li>
</ul>
<p>Depois, a história pode crescer naturalmente.</p>

<h2>Introduza personagens marcantes cedo.</h2>
<p>Os primeiros personagens costumam ser os mais lembrados.</p>
<p>Eles devem demonstrar personalidade imediatamente.</p>

<h2>Exemplo em Deltarune:</h2>
<p>
  Nos primeiros minutos de gameplay, a Susie é apresentada. Ela faz uma grande
  entrada ao entrar na sala que faz todos ficarem em silêncio e com medo, e
  então ameaça Kris no corredor da escola. Isso mostra que ela é uma personagem
  perigosa e com possíveis más intenções.
</p>

