<p>
  O seu objetivo é fazer o jogador criar perguntas na própria cabeça logo nos
  primeiros minutos. Quando existe uma dúvida interessante, o jogador
  naturalmente quer continuar para descobrir a resposta.
</p>
<p>Evite começar com longos textos explicando toda a história do mundo.</p>
<p>Em vez disso, mostre algo estranho ou inesperado.</p>
<p>Tente surpreender o jogador com algo incite a curiosidade dele.</p>

<h2>Exemplo em Undertale:</h2>
<p>
  No início do jogo, Flowey parece ser um personagem amigável, mas poucos
  segundos depois tenta matar o protagonista. Isso desperta perguntas como:
</p>
<ul>
  <li>Quem é Flowey?</li>
  <li>Por que ele fez isso?</li>
  <li>Quem realmente pode ser confiável?</li>
</ul>
<p>O jogo responde essas perguntas aos poucos.</p>

