<p>
  No seu guia mestre insira os personagens de sua história. Para cada personagem
  registre nome, idade, aparência, objetivo, personalidade, qualidades,
  defeitos, forma de falar, etc.
</p>
<p>Por exemplo: Toriel de Undertale</p>
<p>
  O traço mais marcante dela é que ela é uma figura materna e superprotetora
  para o jogador. Isso é uma qualidade e defeito, qualidade pois ela ensina o
  jogador as regras do mundo, mas defeito por ela não deixar o jogador explorar
  o mundo, cuidando muito do jogador e colocando a vida dele até mesmo acima da
  própria.
</p>

