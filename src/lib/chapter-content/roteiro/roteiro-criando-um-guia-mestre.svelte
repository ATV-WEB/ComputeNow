<p>
  Não são todos os jogos que contam uma história. Alguns têm foco na gameplay e
  em um sistema de ganhar pontos, subir ranks, etc. Porém, se você quer contar
  uma história no seu jogo, então os módulos deste curso para criação de roteiro
  são importantes.
</p>

<h2>A regra do “E se…?”</h2>
<p>
  Quando se está criando um mundo fictício para sua história, tudo começa com um
  “E se…?”
</p>
<p>Por exemplo:</p>
<blockquote>E se fosse uma história sobre humanos e monstros?</blockquote>
<p>Começando simples, depois você poderá expandir o conceito.</p>

<h2>Crie um guia mestre para o seu mundo e seus personagens</h2>
<p>
  Para o mundo, você pode anotar coisas como: Em que tempo se passa essa
  história? Se é um mundo normal ou de fantasia, se for de fantasia: Como surgiu
  esse mundo? Qual a backstory dele (passado do mundo)? etc.
</p>
<p>
  É recomendado anotar as regras desse mundo. Por exemplo, se for um mundo com
  poderes mágicos: Quais os limites desses poderes? O que eles podem e não podem
  fazer?
</p>
<p>Quais as consequências das ações do personagem principal?</p>
<p>
  Quanto mais claras forem as regras do mundo, menos furos de roteiro a história
  terá. Busque estabelecer as regras e não burlar elas.
</p>
<p>
  Busque anotar locais importantes em que o jogador irá estar durante a gameplay
</p>
<p>
  Coisas como: Aparência do local, habitantes, história e importância na
  narrativa.
</p>
<p>Deixa o mundo mais vivo se os seus locais forem dinâmicos.</p>
<p>
  Por exemplo, em Undertale, uma das áreas é as Ruínas, uma grande construção
  antiga com paredes roxas. Existem folhas vermelhas espalhadas por todo o
  local, mas nenhuma árvore a vista até o final da área, onde é revelado (caso
  você interaja com ela) que há uma única árvore cujas folhas caem assim que
  crescem e se espalham por toda a área
</p>
<p>
  Isso faz com que exista um motivo lógico e orgânico no mundo para o design de
  uma área
</p>

