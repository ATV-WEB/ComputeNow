<h2>Ideia principal:</h2>
<p>Um protagonista interessante não é definido pelo seu poder, mas pela sua personalidade, seus defeitos e pelas escolhas que faz.</p>
<p>Jogadores criam conexão com personagens humanos, não com personagens perfeitos.</p>

<p>Um bom protagonista costuma possuir:</p>
<ul>
  <li>Desejos;</li>
  <li>Medos;</li>
  <li>Defeitos;</li>
  <li>Dúvidas;</li>
  <li>Valores;</li>
  <li>Conflitos internos.</li>
</ul>

<h2>Exemplo em Undertale:</h2>
<p>Undertale é um jogo que é determinado pelas escolhas do jogador. O jogador controla Frisk que é um protagonista silencioso que faz apenas o que o jogador quer fazer. Isso faz com que seus erros e acertos sejam os mesmos do jogador. As decisões são determinadas pelo jogador: um humano com defeitos humanos.</p>
