<h2>Ideia principal:</h2>
<p>
  Um bom plot twist funciona porque as pistas possuem duas interpretações
  possíveis.
</p>
<p>
  Durante quase toda a história, o jogador interpreta as informações de uma
  maneira. Depois da revelação, ele percebe que aquelas mesmas pistas sempre
  apontavam para outra resposta.
</p>
<p>
  Não é preciso esconder as evidências. Basta direcionar a atenção do jogador
  para a interpretação errada.
</p>

<h2>Como aplicar:</h2>
<p>Escreva primeiro a verdade.</p>
<p>Depois pense como os personagens enxergam essa verdade.</p>
<p>Faça o jogador adotar naturalmente esse mesmo ponto de vista.</p>
<p>Após a revelação, todas as pistas devem continuar fazendo sentido.</p>

<h2>Exemplo em Undertale:</h2>
<p>No início, o jogador acredita que Asgore é um rei cruel que mata humanos.</p>
<p>Tudo parece confirmar isso:</p>
<ul>
  <li>Toriel diz que ele mata todas as crianças.</li>
  <li>Os monstros falam dele como alguém poderoso.</li>
  <li>Seu castelo transmite imponência.</li>
</ul>
<p>
  Mas, quando finalmente o encontramos, descobrimos um homem cansado, triste e
  preso às próprias responsabilidades.
</p>
<p>Nada do que ouvimos era mentira.</p>
<p>A interpretação era.</p>
<p>As mesmas informações sustentam duas narrativas:</p>
<ul>
  <li>Antes: "Asgore é um tirano";</li>
  <li>Depois: "Asgore é uma vítima de suas próprias escolhas.”</li>
</ul>

