<h2>Ideia principal:</h2>
<p>
  Conflitos entre personagens criam emoções muito mais fortes do que conflitos
  físicos.
</p>
<p>
  Dois amigos discutindo pode ser mais impactante do que uma luta contra um
  dragão.
</p>
<p>Esses conflitos podem surgir por:</p>
<ul>
  <li>diferenças de valores;</li>
  <li>Culpa;</li>
  <li>Inveja;</li>
  <li>Medo;</li>
  <li>Desconfiança;</li>
  <li>Objetivos incompatíveis.</li>
</ul>

<h2>O erro comum:</h2>
<p>Fazer todos os personagens concordarem sempre.</p>
<p>Sem conflito, não existe crescimento.</p>

<h2>Exemplo em Deltarune:</h2>
<p>
  Susie tem uma visão ingênua da realidade do jogo e quer acreditar no melhor,
  mas Ralsei oculta várias informações sobre o futuro. Quando Susie descobre o
  que vai acontecer por meio da profecia, um conflito acontece.
</p>

