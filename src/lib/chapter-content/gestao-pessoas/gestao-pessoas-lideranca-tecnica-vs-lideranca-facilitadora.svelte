<p>Ao final desta
leitura, você saberá diferenciar dois estilos de liderança muito
comuns, compreenderá em quais momentos cada um funciona melhor e
aprenderá a evitar um dos erros mais frequentes em competições de
ritmo acelerado.</p>
<p>Imagine a
seguinte cena: a equipe decide que o líder será a pessoa que mais
sabe programar ou a mais experiente em arte. Durante o evento, essa
pessoa precisa construir partes difíceis do projeto, corrigir erros
complexos, tirar dúvidas do time, tomar decisões de estrutura e
ainda organizar as entregas. O resultado dessa escolha costuma ser o
esgotamento. O especialista fica completamente sobrecarregado
tentando fazer o trabalho bruto e, ao mesmo tempo, gerenciar o
projeto. Enquanto ele tenta resolver tudo sozinho, o restante do
grupo fica parado esperando instruções. Esse é um erro clássico
em hackathons e game jams.</p>
<p>A <b>liderança
técnica</b> é focada no conteúdo prático e na execução do
projeto. A pessoa com esse perfil costuma dominar as ferramentas
utilizadas, resolver os problemas mais difíceis da área dela e
orientar a equipe sobre a melhor forma de construir o produto. Essa
atuação é valiosa para garantir que a parte técnica do projeto
seja bem feita. No entanto, ter esse conhecimento não significa que
essa mesma pessoa precise assumir a coordenação das pessoas e do
tempo do grupo.</p>
<p>A <b>liderança
facilitadora</b> tem um foco diferente: o seu objetivo principal é
remover obstáculos do caminho para que a equipe consiga trabalhar
sem interrupções. Quem atua de forma facilitadora cuida da
organização das tarefas, acompanha o ritmo do grupo, ajuda a manter
a comunicação fluida e garante que todos saibam o que deve ser
feito a seguir. O líder facilitador não precisa ser a pessoa mais
avançada em programação ou design; ele precisa garantir que quem
entende dessas áreas tenha espaço e tranquilidade para produzir.</p>
