<p>Ao final deste capítulo, você
saberá identificar rapidamente as habilidades da sua equipe,
conseguirá distribuir tarefas conforme as competências de cada
integrante e evitará perdas de tempo causadas por uma má divisão
de trabalho.</p>
<p>A divisão de tarefas é uma das
decisões mais importantes de uma liderança e deve acontecer nos
primeiros minutos da equipe, logo após a definição da ideia.
Quando o tempo é curto, é natural que todos queiram começar a
produzir imediatamente, mas investir cerca de dez minutos para
entender os pontos fortes do grupo economiza horas de retrabalho mais
adiante. Uma equipe eficiente não é aquela formada apenas pelas
pessoas mais experientes, mas sim a que consegue aproveitar o
potencial de cada integrante da melhor forma.</p>
<p>Na hora de mapear o que as pessoas
sabem fazer, é comum pensar apenas nas funções tradicionais, como
programação, arte, áudio e escrita. No entanto, existem outras
capacidades que fazem uma diferença enorme durante a competição.
Saber se comunicar com clareza, organizar o fluxo de tarefas, testar
o projeto procurando erros, pesquisar soluções rápidas ou
apresentar o trabalho para a banca são talentos valiosos. Em um
hackathon, por exemplo, um colega articulado pode destacar o projeto
na apresentação final. Em uma game jam, uma pessoa detalhista nos
testes pode encontrar falhas críticas que passariam despercebidas.</p>
<p>Para descobrir esses pontos fortes
de maneira eficiente, em vez de fazer uma pergunta genérica sobre o
que cada um sabe fazer, prefira questionamentos práticos. Pergunte
em quais ferramentas a pessoa já se sente confortável, qual tipo de
atividade ela tem mais interesse em realizar no momento, o que
prefere evitar e se já viveu uma experiência parecida antes. Com
essas respostas em mãos, fica muito mais fácil visualizar onde cada
um pode render melhor.</p>
<p>Construir uma anotação simples
relacionando o nome de cada integrante, sua habilidade principal e
uma habilidade secundária ajuda a manter a organização. Dessa
forma, quando alguém conclui uma etapa do trabalho, o líder já
sabe para onde direcionar essa pessoa sem que ela fique ociosa.</p>
<p>Também é importante ter cuidado
para não deixar especialistas isolados em funções vitais do
projeto. Se apenas um integrante entende determinada ferramenta e
precisa se ausentar ou enfrenta um problema técnico complexo, toda a
produção pode travar. Compartilhar conhecimentos básicos e manter
as decisões importantes registradas reduz significativamente esse
risco. Conforme o evento avança, o mapa de habilidades pode e deve
se transformar, permitindo que os integrantes ajudem em áreas
diferentes sempre que surgir a oportunidade.</p>
<p><b>Recapitulação</b></p>
<p>Conhecer a fundo as capacidades da
equipe economiza tempo e evita gargalos. Liderar a divisão de
tarefas envolve olhar para além das competências técnicas e manter
o direcionamento do grupo atualizado durante todo o evento.</p>
