<p>Ao final deste capítulo, você
saberá identificar o Feature Creep, aprenderá formas de impedir que
ele comprometa a sua entrega e entenderá como e quando dizer &quot;não&quot;
para manter o foco do grupo.</p>
<p>Tudo costuma começar de forma muito
positiva: a equipe tem uma ideia simples e alinhada, mas, conforme o
desenvolvimento avança, surgem sugestões tentadoras como colocar
modos extras, novas habilidades, opções de personalização ou
mecânicas mais complexas. O problema nunca é a qualidade dessas
ideias, mas sim o acúmulo descontrolado delas. Esse fenômeno é
conhecido como Feature Creep, o crescimento invisível do escopo que
transforma um projeto viável em algo impossível de terminar no
prazo.</p>
<p>Esse acúmulo de funcionalidades
acontece de maneira sutil. Cada nova sugestão parece leve e rápida
de fazer, mas a soma de todas elas cria um peso enorme sobre o grupo.
É como colocar pedras pequenas dentro de uma mochila: uma única
pedra não faz diferença, mas vinte pedras impedem qualquer pessoa
de andar. Isso costuma acontecer por causa do entusiasmo inicial, do
medo de apresentar algo simples demais ou da tentação de comparar o
projeto com o de equipes vizinhas.</p>
<p>Para combater esse problema antes
que ele destrua a entrega, o grupo deve passar qualquer nova ideia
por três filtros rápidos. O primeiro é perguntar se aquela
funcionalidade é realmente essencial para o projeto funcionar. O
segundo é calcular o tempo real que ela levará para ser feita,
lembrando que estimativas costumam falhar. O terceiro é decidir o
que será removido do planejamento para dar lugar à nova ideia, pois
tentar adicionar algo sem tirar nada apenas incha o projeto.</p>
<p>Saber dizer &quot;não&quot; para
boas sugestões é uma das tarefas mais importantes e difíceis da
liderança. Negar uma funcionalidade não significa que a ideia seja
ruim, mas sim que o tempo é limitado. Uma ferramenta útil para
evitar frustrações é criar uma lista de desejos para o pós-evento.
Assim, as ideias interessantes ficam salvas para o futuro e a equipe
consegue manter a atenção no presente. Em maratonas de
desenvolvimento, projetos menores, estáveis, criativos e bem
acabados costumam se destacar muito mais do que projetos gigantescos
que não funcionam direito.</p>
<p><b>Recapitulação</b></p>
<p>O Feature Creep é o inchaço
descontrolado de ideias que ameaça a entrega do projeto. Liderar
exige saber recusar acréscimos fora de hora e manter o time focado
em entregar um produto completo dentro do prazo.</p>
