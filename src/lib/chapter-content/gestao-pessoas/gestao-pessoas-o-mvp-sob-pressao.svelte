<p>Ao final deste capítulo, você
entenderá o conceito de Produto Mínimo Viável (MVP), saberá como
aplicá-lo durante a pressão de um evento e aprenderá a priorizar
apenas o que realmente precisa existir no seu projeto.</p>
<p>Em competições com tempo reduzido,
como hackathons e game jams, a capacidade de focar no que é
essencial determina quem consegue entregar o projeto e quem fica pelo
caminho. É aqui que entra o conceito de Produto Mínimo Viável,
conhecido pela sigla MVP. Ele representa a menor versão funcional do
seu projeto que ainda consegue entregar a ideia principal ao público.
Em vez de tentar construir um produto gigante do início ao fim, a
equipe se concentra em colocar no ar aquilo que dá vida à proposta
principal.</p>
<p>A forma mais simples de descobrir o
seu MVP em um momento de estresse é fazer uma pergunta direta para o
grupo: se a entrega fosse daqui a poucas horas, o que precisaria
estar funcionando obrigatoriamente? A resposta revela o verdadeiro
coração do projeto. Pense, por exemplo, em um jogo de corrida. No
início, a equipe pode sonhar com dez pistas, oito carros
customizáveis, modo online e efeitos de chuva. No entanto, o MVP
desse mesmo jogo precisa apenas de uma pista, um carro, a mecânica
de aceleração funcionando e uma forma clara de vencer ou perder.
Todo o restante é opcional e só deve ser desenvolvido se restar
tempo sobressalente.</p>
<p>Para organizar essa construção sem
se perder, a equipe pode classificar as funcionalidades em três
camadas simples. A primeira camada é a essencial, onde ficam os
itens sem os quais o projeto simplesmente não funciona. A segunda é
a importante, que reúne melhorias que deixam a experiência mais
rica, mas que não impedem o uso se faltarem. A terceira é a camada
extra, composta por detalhes interessantes, mas totalmente
descartáveis caso o prazo aperte. A liderança deve garantir que
todos conheçam essa ordem para não investirem energia no lugar
errado.</p>
<p>No final do evento, os jurados e o
público vão avaliar aquilo que conseguem testar e experimentar na
prática. Uma funcionalidade incrível que não funciona ou está
cheia de erros vale muito menos do que uma estrutura simples rodando
perfeitamente. Conforme o relógio avança, é natural e saudável
que o MVP diminua para se ajustar ao tempo restante. Fazer esses
ajustes não é sinal de fracasso, mas sim de maturidade e foco do
time na entrega final.</p>
<p><b>Recapitulação</b></p>
<p>O MVP é a menor versão funcional
de uma ideia e deve ser a prioridade da equipe. Entregar um projeto
pequeno e funcionando traz resultados infinitamente melhores do que
tentar apresentar uma ideia grande pela metade.</p>
