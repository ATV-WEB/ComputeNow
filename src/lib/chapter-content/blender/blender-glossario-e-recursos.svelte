<h2>Glossário</h2>
<div class="table-scroll"><table><thead><tr><th>Termo</th><th>Significado</th></tr></thead><tbody>
  <tr><td>Objeto</td><td>Elemento presente na cena.</td></tr>
  <tr><td>Malha (Mesh)</td><td>Conjunto de vértices, arestas e faces.</td></tr>
  <tr><td>Viewport</td><td>Área de visualização 3D.</td></tr>
  <tr><td>Render</td><td>Imagem final gerada pelo Blender.</td></tr>
  <tr><td>Material</td><td>Aparência do objeto.</td></tr>
  <tr><td>Shader</td><td>Cálculo que define a reação do material à luz.</td></tr>
  <tr><td>Topologia</td><td>Organização da geometria.</td></tr>
  <tr><td>Escultura</td><td>Modelagem livre semelhante à argila.</td></tr>
</tbody></table></div>

