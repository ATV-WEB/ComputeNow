<h3>Navegação da câmera</h3>
<h4>Movimentos básicos</h4>
<ul>
  <li>Rotacionar: botão do meio do mouse.</li>
  <li>Mover: Shift + botão do meio do mouse.</li>
  <li>Zoom: roda do mouse.</li>
</ul>

<h4>Exemplo prático</h4>
<ul>
  <li>Abrir o Blender.</li>
  <li>Rotacionar a visão ao redor do cubo inicial.</li>
  <li>Mover a câmera lateralmente.</li>
  <li>Aproximar e afastar a cena.</li>
</ul>
<p>
  Dica: o aluno deve praticar a navegação por alguns minutos antes de iniciar a
  modelagem.
</p>

<h3>Selecionando objetos</h3>
<ul>
  <li>Clique esquerdo: seleciona um objeto.</li>
  <li>Shift + clique esquerdo: seleciona vários objetos.</li>
  <li>Tecla B: seleção em caixa.</li>
</ul>

<h3>Transformações básicas</h3>
<h4>Mover (Move)</h4>
<p>Atalho: G</p>
<h4>Rotacionar (Rotate)</h4>
<p>Atalho: R</p>
<h4>Escalar (Scale)</h4>
<p>Atalho: S</p>
<p>Esses três comandos são os mais utilizados durante toda a modelagem 3D.</p>

<h3>Modos do Blender</h3>
<h4>Object Mode</h4>
<p>Utilizado para selecionar e transformar objetos inteiros.</p>
<h4>Edit Mode</h4>
<p>Utilizado para editar a geometria do objeto.</p>
<p>Atalho: Tab</p>

<h3>Adicionando objetos</h3>
<h4>Caminho</h4>
<p>Adicionar → Malha → Cubo</p>
<p>Outros objetos disponíveis:</p>
<ul>
  <li>Esfera;</li>
  <li>Cilindro;</li>
  <li>Cone;</li>
  <li>Plano.</li>
</ul>

<h4>Exemplo prático</h4>
<p>Criar:</p>
<ul>
  <li>um cubo;</li>
  <li>uma esfera;</li>
  <li>um cilindro.</li>
</ul>
<p>Depois mover cada objeto para uma posição diferente.</p>

<h3>Elemento Interativo</h3>
<p>
  Elemento interativo: o usuário pode clicar em um objeto e usar botões virtuais
  de mover, rotacionar e escalar.
</p>
