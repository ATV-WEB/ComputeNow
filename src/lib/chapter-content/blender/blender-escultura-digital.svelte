<h3>Controle do pincel</h3>
<ul>
  <li>F: altera o tamanho do pincel.</li>
  <li>Shift + F: altera a força do pincel.</li>
</ul>

<h3>Exercícios</h3>
<p>Esculpir:</p>
<ul>
  <li>uma pedra;</li>
  <li>uma maçã;</li>
  <li>uma bola de neve.</li>
</ul>
<p>Esses objetos ajudam o aluno a compreender o funcionamento dos pincéis.</p>

<h3>Elemento Interativo</h3>
<p>
  Elemento interativo: o usuário pode aumentar ou diminuir uma esfera simulando
  o uso de um pincel de escultura.
</p>
