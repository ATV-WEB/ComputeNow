<h3>Boa topologia</h3>
<ul>
  <li>Faces organizadas;</li>
  <li>Fluxo uniforme;</li>
  <li>Predominância de quads.</li>
</ul>

<h3>Má topologia</h3>
<ul>
  <li>Triângulos excessivos;</li>
  <li>Geometria irregular;</li>
  <li>Dificuldade para editar o modelo.</li>
</ul>

<h3>Quads e N-gons</h3>
<h4>Quads</h4>
<p>Faces com quatro lados. São as mais utilizadas na modelagem.</p>
<h4>N-gons</h4>
<p>
  Faces com mais de quatro lados. Podem causar problemas em algumas operações.
</p>
