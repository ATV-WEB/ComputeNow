<h3>Conceitos</h3>
<ul>
  <li>Nodes: blocos de informação;</li>
  <li>Conexões: ligam os nodes;</li>
  <li>Fluxo de informação: determina o resultado final do material.</li>
</ul>

<h3>Exemplos</h3>
<ul>
  <li>Material metálico;</li>
  <li>Material de pedra;</li>
  <li>Material emissivo (que emite luz).</li>
</ul>
<p>
  Neste curso os Shader Nodes serão apenas apresentados, pois pertencem a um
  nível mais avançado de estudo.
</p>
