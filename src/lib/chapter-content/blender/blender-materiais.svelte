<h3>Conceitos básicos</h3>
<h4>Cor Base (Base Color)</h4>
<p>Define a cor principal do objeto.</p>
<h4>Rugosidade (Roughness)</h4>
<p>Controla o brilho da superfície.</p>
<h4>Reflexão</h4>
<p>Define o quanto o material reflete o ambiente.</p>

