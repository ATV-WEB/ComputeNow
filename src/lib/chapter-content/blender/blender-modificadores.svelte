<h2>Modificadores</h2>
<h3>O que são?</h3>
<p>Ferramentas automáticas que modificam um objeto sem alterar sua geometria original.</p>

<h3>Exemplos</h3>
<ul><li>Subdivision Surface;</li><li>Mirror;</li><li>Solidify;</li><li>Bevel.</li></ul>
<p>Neste módulo os modificadores serão apenas apresentados, sem aprofundamento.</p>

<h3>Elemento Interativo</h3>
<p>Elemento interativo: ligar e desligar um modificador para observar a diferença no modelo.</p>
