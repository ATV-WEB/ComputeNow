<h3>Vértices (Vertices)</h3>
<p>Pontos individuais no espaço 3D.</p>
<h3>Arestas (Edges)</h3>
<p>Linhas que conectam os vértices.</p>
<h3>Faces</h3>
<p>Superfícies formadas pelas arestas.</p>

<h3>Exemplo prático</h3>
<p>Um cubo possui:</p>
<ul>
  <li>8 vértices</li>
  <li>12 arestas</li>
  <li>6 faces</li>
</ul>
<p>Ou seja, uma geometria básica.</p>
