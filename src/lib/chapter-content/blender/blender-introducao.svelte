<h2>Objetivo Geral</h2>
<p>Apresentar aos alunos os fundamentos da computação gráfica 3D utilizando o software Blender, permitindo a criação de modelos simples, personagens básicos, esculturas digitais e pequenas animações introdutórias.</p>

<p>Ao final do módulo, o aluno será capaz de:</p>
<ul>
  <li>Navegar pela interface do Blender;</li>
  <li>Criar e modificar objetos 3D;</li>
  <li>Compreender como um modelo é construído;</li>
  <li>Realizar uma escultura digital simples;</li>
  <li>Aplicar materiais básicos;</li>
  <li>Produzir uma imagem renderizada de um projeto simples.</li>
</ul>

<h2>Introdução ao Blender</h2>
<h3>O que é o Blender?</h3>
<p>O Blender é um software gratuito e de código aberto utilizado para criação de conteúdos em computação gráfica 3D.</p>
<p>Com ele é possível desenvolver:</p>
<ul>
  <li>Modelos 3D;</li><li>Personagens;</li><li>Cenários;</li><li>Objetos para jogos;</li><li>Animações;</li><li>Filmes;</li><li>Simulações físicas;</li><li>Projetos para impressão 3D.</li>
</ul>
<p>O Blender é utilizado por artistas, desenvolvedores de jogos, arquitetos, engenheiros e até estúdios independentes de animação.</p>

<h3>Onde encontramos modelos 3D no dia a dia?</h3>
<p>A computação gráfica está presente em diversos lugares:</p>
<ul>
  <li>Jogos eletrônicos;</li><li>Filmes de animação;</li><li>Aplicativos de celular;</li><li>Arquitetura;</li><li>Engenharia;</li><li>Medicina;</li><li>Impressão 3D.</li>
</ul>
<p>Você sabia? O Blender é totalmente gratuito e pode ser instalado em computadores pessoais sem custo de licença.</p>

<h3>Elemento Interativo</h3>
<p>Elemento interativo: apresentar imagens de jogos, filmes e objetos reais e pedir que o aluno identifique quais utilizam computação gráfica 3D.</p>
